BY_PREFIX = {w[0]: w for w in WORKS}
# 先比對較長的 prefix (πο 先於 π, Ζι 先於 Ζ…)
PREFIXES = sorted(BY_PREFIX, key=len, reverse=True)


def works_for_page(page: int):
    return [w for w in WORKS if w[3] <= page <= w[4]]


def prefix_of(sig: str):
    """sig 開頭所屬的書名縮寫 (最長比對)，無則 None"""
    for p in PREFIXES:
        if sig.startswith(p):
            return p
    return None


def work_name(sig: str):
    """完整縮寫 -> 通行縮寫；分卷的合刊書依卷號區分"""
    p = prefix_of(sig or "")
    if not p:
        return None
    book = sig[len(p):]
    if p == "Α":
        return "APo." if book[:1] in ("γ", "δ") else "APr."
    if p == "τ":
        return "SE" if book.startswith("ι") else "Top."
    return BY_PREFIX[p][2]


