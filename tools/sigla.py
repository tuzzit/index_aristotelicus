DIOGENES = "http://localhost:8888/Diogenes.cgi?JumpTo=tlg,0086,{work}:{loc}"
GREEK_BOOK = "αβγδεζηθικλμν"


def diogenes_loc(work, page, col, line, sig=None, ch=None):
    """回傳 Diogenes 位置字串；無法對應時回傳空字串。

    Bekker 頁碼作品：page+col:line
    MM (TLG 022 依 Book/chapter/section/line)：以 Bonitz 的卷號＋章 → book:chapter
    """
    if work == "MM":
        book = (sig or "")[2:3]
        chn = re.match(r"\d+", ch or "")
        if book in GREEK_BOOK and chn:
            return f"022:{GREEK_BOOK.index(book) + 1}:{chn.group(0)}"
        return ""
    w = TLG.get(work)
    if not (w and page and col and line):
        return ""
    return f"{w}:{page}{col}:{str(line).split('-')[0]}"


def diogenes_url(work, page, col, line, sig=None, ch=None):
    loc = diogenes_loc(work, page, col, line, sig, ch)
    return DIOGENES.format(work=loc.split(":", 1)[0], loc=loc.split(":", 1)[1]) if loc else ""
